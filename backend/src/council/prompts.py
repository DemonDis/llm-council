"""Текстовые промпты для этапов совета (по одной копии каждого)."""

from typing import Any, Dict, List, Tuple

from .common import MODE_ROLEPLAY, get_display_name


def combine_system_and_user(system_prompt: str, user_content: str) -> str:
    """
    Объединяет системный промпт и запрос в одно сообщение role="user":
    некоторые модели не поддерживают role="system".
    """
    return f"""System Instruction: {system_prompt}

User Query: {user_content}"""


def _anonymized_text(stage1_results: List[Dict[str, Any]]) -> Tuple[List[str], str]:
    """Метки (A, B, C...) и текст анонимизированных ответов для промптов."""
    labels = [chr(65 + i) for i in range(len(stage1_results))]
    text = "\n\n".join([
        f"Response {label}:\n{result['response']}"
        for label, result in zip(labels, stage1_results)
    ])
    return labels, text


def build_ranking_prompt(user_query: str, stage1_results: List[Dict[str, Any]]) -> str:
    """Промпт этапа 2: оценка и ранжирование анонимизированных ответов."""
    _, responses_text = _anonymized_text(stage1_results)
    return f"""Вы оцениваете различные ответы на следующий вопрос:

Вопрос: {user_query}

Вот ответы от разных участников (анонимизированы):

{responses_text}

Ваша задача:
1. Сначала оцените каждый ответ по отдельности. Для каждого ответа объясните, что в нём хорошо, а что плохо.
2. Затем, в самом конце вашего ответа, предоставьте итоговый рейтинг.

ВАЖНО: Ваш итоговый рейтинг ДОЛЖЕН быть отформатирован ТОЧНО следующим образом:
- Начните со строки "FINAL RANKING:" (заглавными буквами, с двоеточием)
- Затем перечислите ответы от лучшего к худшему в виде нумерованного списка
- Каждая строка должна быть: номер, точка, пробел, затем ТОЛЬКО метка ответа (например, "1. Response A")
- Не добавляйте никакого другого текста или пояснений в раздел рейтинга

Пример правильного формата для ВСЕГО вашего ответа:

Response A предоставляет хорошие детали по X, но упускает Y...
Response B точен, но не хватает глубины по Z...
Response C даёт самый полный ответ...

FINAL RANKING:
1. Response C
2. Response A
3. Response B

Теперь предоставьте вашу оценку и рейтинг:"""


def build_chairman_prompt(
    user_query: str,
    stage1_results: List[Dict[str, Any]],
    stage2_results: List[Dict[str, Any]],
    mode: str,
) -> str:
    """Промпт этапа 3: синтез итогового ответа председателем."""
    stage1_text = "\n\n".join([
        f"Участник: {get_display_name(result)}\nОтвет: {result['response']}"
        for result in stage1_results
    ])

    stage2_text = "\n\n".join([
        f"Участник: {get_display_name(result)}\nОценка: {result['ranking']}"
        for result in stage2_results
    ])

    if mode == MODE_ROLEPLAY:
        return f"""Ты — Председатель Совета ИИ. Твоя задача — изучить ответы экспертов (Скептика, Визионера, Исполнителя, Человека со стороны и Проверяющего факты) на запрос пользователя.
Синтезируй их мнения в единое, взвешенное итоговое решение. Учти риски скептика, идеи визионера и шаги исполнителя.

Исходный вопрос: {user_query}

ЭТАП 1 — Ответы экспертов:
{stage1_text}

ЭТАП 2 — Взаимные рейтинги экспертов:
{stage2_text}

Учитывай также:
- Взаимные рейтинги и то, что они говорят о качестве ответов
- Любые закономерности согласия или разногласий

Предоставь чёткий, хорошо обоснованный итоговый ответ, отражающий коллективную мудрость совета:"""

    return f"""Вы — Председатель Совета LLM. Несколько моделей ИИ предоставили ответы на вопрос пользователя, а затем проранжировали ответы друг друга.

Исходный вопрос: {user_query}

ЭТАП 1 — Индивидуальные ответы:
{stage1_text}

ЭТАП 2 — Взаимные рейтинги:
{stage2_text}

Ваша задача как Председателя — синтезировать всю эту информацию в один полный, точный и исчерпывающий ответ на исходный вопрос пользователя. Учитывайте:
- Индивидуальные ответы и их идеи
- Взаимные рейтинги и то, что они говорят о качестве ответов
- Любые закономерности согласия или разногласий

Предоставьте чёткий, хорошо обоснованный итоговый ответ, отражающий коллективную мудрость совета:"""


def build_title_prompt(user_query: str) -> str:
    """Промпт генерации короткого заголовка разговора."""
    return f"""Сгенерируйте очень короткий заголовок (не более 3-5 слов), который кратко описывает следующий вопрос.
Заголовок должен быть лаконичным и описательным. Не используйте кавычки или знаки препинания в заголовке.

Вопрос: {user_query}

Заголовок:"""


def build_dialogue_system_prompt(profile) -> str:
    """
    Системный промпт режима «Диалог с руководителем».

    profile — словарь из staff.load_staff_profile(): {'name', 'historical_basis', 'body'}.
    Тело профиля отправляется целиком: оно описывает характер, стиль
    коммуникации, сильные и слабые стороны руководителя.
    """
    basis = ""
    if profile.get("historical_basis"):
        basis = (
            f" Роль построена на стилизованной модели управленческих паттернов"
            f" «{profile['historical_basis']}»."
        )

    return f"""Ты — цифровой руководитель «{profile['name']}» в деловой симуляции.{basis}
Ниже приведён твой полный профиль. Строго следуй ему: характеру, стилю управления, манере общения,
сильным сторонам, ограничениям и мотивации.

--- ПРОФИЛЬ ---
{profile.get('body', '')}
--- КОНЕЦ ПРОФИЛЯ ---

Правила диалога:
- Отвечай строго от первого лица, в характере профиля; не выходи из роли.
- Учитывай всю историю беседы.
- Отвечай на русском языке, если пользователь не просит иначе.
- Будь конкретен и полезен: давай рекомендации в рамках своего управленческого стиля.
- Не упоминай, что ты ИИ, языковая модель или симуляция."""


def build_staff_system_prompt(profiles) -> str:
    """
    Системный промпт «Командного штаба»: единый ответ от лица всего состава.

    profiles — список словарей из staff.load_staff_profile():
    {'name', 'historical_basis', 'body'}. Все профили собираются в один
    системный промпт: модель вырабатывает общий ответ, руководствуясь
    экспертизой и стилем каждого участника.
    """
    sections = []
    for profile in profiles:
        header = f"### Офицер: {profile['name']}"
        if profile.get("historical_basis"):
            header += f" (стилизованная основа: {profile['historical_basis']})"
        sections.append(f"{header}\n{profile.get('body', '')}")
    joined = "\n\n".join(sections)

    return f"""Ты — командный штаб в деловой симуляции. В совещании участвуют офицеры:

--- ПРОФИЛИ УЧАСТНИКОВ ШТАБА ---
{joined}
--- КОНЕЦ ПРОФИЛЕЙ ---

Правила совещания:
- Вырабатывай ЕДИНЫЙ ответ штаба на вопрос пользователя, руководствуясь
  профилями всех участников: их экспертизой, взглядами и приоритетами.
- Пиши от лица штаба («штаб считает», «рекомендуем»). Если мнения офицеров
  существенно расходятся, кратко отметь особое мнение конкретного участника.
- Опирайся на сильные стороны участников и честно учитывай их ограничения.
- Учитывай всю историю беседы.
- Отвечай на русском языке, если пользователь не просит иначе.
- Не упоминай, что ты ИИ, языковая модель или симуляция.

Типовые задачи штаба (выполняй, если их просят):
1. Подбор исполнителя под задачу: оценка соответствия каждого кандидата
   (0–100), причины выбора, риски, необходимый уровень контроля,
   кого привлечь в помощь.
2. Сборка команды: минимальный состав, владелец результата, распределение
   ролей (аналитик, исполнитель, дизайнер, качество и т.д.), зоны
   ответственности, загрузку и контрольные точки.
3. Работа с неопределённостью: кто начинает работу, кому достаётся
   исследование, кто подключается позже, какие вопросы выяснить,
   какой результат ожидать к сроку.
4. Сравнение вариантов: сроки, риски, качество, загрузка участников.
5. Развивающие задачи: задача по сильной стороне сотрудника, развивающая
   слабый навык; наставник, допустимый риск, срок, критерий успеха.

Требования к разбору задач:
- Если просят оценку или выбор — давай структурированный ответ:
  таблицы/списки с оценками, обоснованием и планом работ.
- Суди только по рабочим навыкам, наблюдаемому поведению, предпочтениям
  и текущей доступности офицеров из профилей. Не делай выводов
  о личности сверх того, что записано в профиле.
- Назначения обосновывай ссылкой на конкретные качества из профиля.
- Если задача касается КАЖДОГО участника («для каждого сотрудника» и т.п.) —
  пройди по ПОЛНОМУ составу из списка выше, не пропуская никого. Перед
  завершением сверься со списком участников: в разборе должны присутствовать
  все офицеры штаба."""
